// 고정 양력 공휴일 폴백 (사전 테이블 외 연도 대비)
const SOLAR_FIXED_HOLIDAYS: Record<string, string> = {
  '01-01': '신정',
  '03-01': '삼일절',
  '05-05': '어린이날',
  '06-06': '현충일',
  '08-15': '광복절',
  '10-03': '개천절',
  '10-09': '한글날',
  '12-25': '성탄절',
};

/**
 * 특정 날짜(YYYY-MM-DD)의 대한민국 공휴일 정보 반환
 */
export function getKoreanHoliday(dateStr: string): KoreanHoliday | null {
  if (!dateStr || dateStr.length < 10) return null;

  // 1. 사전 정의된 연도별 공휴일 확인
  const definedName = HOLIDAY_MAP[dateStr];
  if (definedName) {
    return { date: dateStr, name: definedName };
  }

  // 2. 고정 양력 공휴일 폴백 (MM-DD)
  const mmdd = dateStr.slice(5, 10);
  const fixedName = SOLAR_FIXED_HOLIDAYS[mmdd];
  if (fixedName) {
    return { date: dateStr, name: fixedName };
  }

  return null;
}

/**
 * 해당 날짜가 대한민국 공휴일인지 여부
 */
export function isKoreanHoliday(dateStr: string): boolean {
  return getKoreanHoliday(dateStr) !== null;
}
